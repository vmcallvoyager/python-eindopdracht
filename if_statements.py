# Cijfers voor drie vakken
variable1 = 5
variable2 = 10
variable3 = 7

# Bereken het gemiddelde
gemiddelde = (variable1 + variable2 + variable3) / 3

print("Gemiddelde:", gemiddelde)

if gemiddelde >= 5.5 and variable1 >= 4 and variable2 >= 4 and variable3 >= 4:
    print("Geslaagd!")
else:
    print("Gezakt!")
